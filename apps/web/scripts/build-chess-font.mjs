#!/usr/bin/env node
/**
 * Generates lib/plugins/fonts/dejavu-chess.ts: a base64-inlined subset of
 * DejaVu Sans holding just the twelve Unicode chess pieces (U+2654-265F) the
 * chess puzzle diagrams draw with. Not part of the app build or runtime; run
 * once (`node scripts/build-chess-font.mjs` from apps/web) and commit the output.
 *
 * DejaVu Sans is under the Bitstream Vera / DejaVu free font license, which
 * allows embedding and redistribution. (The Lichess piece artwork is CC BY-SA,
 * so it's deliberately not used.) Base64-inlined for the same reason as the
 * kanji font: see build-kanji-font.mjs.
 */

import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import subsetFont from "subset-font";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT_TS_PATH = path.join(__dirname, "../lib/plugins/fonts/dejavu-chess.ts");
const FONT_URL = "https://cdn.jsdelivr.net/npm/dejavu-fonts-ttf@2.37.3/ttf/DejaVuSans.ttf";

const glyphs = Array.from({ length: 12 }, (_, i) => String.fromCodePoint(0x2654 + i)).join("");
const full = Buffer.from(await fetch(FONT_URL).then((r) => r.arrayBuffer()));
const subset = await subsetFont(full, glyphs, { targetFormat: "truetype" });

await writeFile(
  OUT_TS_PATH,
  `// Generated by scripts/build-chess-font.mjs — do not hand-edit.
// DejaVu Sans (Bitstream Vera / DejaVu free font license), subset to the
// twelve Unicode chess pieces U+2654-265F. License: ./DEJAVU-LICENSE.txt.

export const DEJAVU_CHESS = "data:font/ttf;base64,${subset.toString("base64")}";
`,
);
console.error(`Wrote ${subset.length}-byte subset to ${OUT_TS_PATH}`);
